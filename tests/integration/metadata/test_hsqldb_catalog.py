"""``HSQLDBCatalog`` contra un HSQLDB real en memoria por JDBC (``jaydebeapi``) con ``DbapiCatalogExecutor`` (A6).

Requiere ``UTIL_BBDD_TEST_HSQLDB_JAR`` (ruta al ``hsqldb-2.x.jar``), Java (``JAVA_HOME`` si no se encuentra solo) y el
paquete ``jaydebeapi``. Sin ellos, el módulo se salta. El registry JSON anterior fallaba con HSQLDB 2.7.4 en 9 de 16
consultas (H-19, sesión 2026-10-03-metadata-centralization); este test fija lo que el dialecto nuevo sí lee.
"""

from __future__ import annotations

import importlib.util
import os

from collections.abc import Iterator
from typing import Any

import pytest

from util_bbdd.metadata import ALL_KINDS, CatalogSource, Kind, RoutineKey, get_catalog_dialect
from util_bbdd.metadata.source import DbapiCatalogExecutor

JAR_ENV = "UTIL_BBDD_TEST_HSQLDB_JAR"

pytestmark = [
    pytest.mark.integration,
    pytest.mark.skipif(not os.environ.get(JAR_ENV), reason=f"{JAR_ENV} no definida"),
    pytest.mark.skipif(importlib.util.find_spec("jaydebeapi") is None, reason="paquete jaydebeapi no instalado"),
]

DDL = [
    "CREATE SCHEMA ZZ_GOLD",
    "SET SCHEMA ZZ_GOLD",
    "CREATE TABLE PARENT (ID INTEGER GENERATED BY DEFAULT AS IDENTITY, CODE VARCHAR(20) NOT NULL, "
    "AMOUNT NUMERIC(12,2) DEFAULT 0, CONSTRAINT PK_PARENT PRIMARY KEY (ID), CONSTRAINT UK_PARENT_CODE UNIQUE (CODE), "
    "CONSTRAINT CK_AMOUNT CHECK (AMOUNT >= 0))",
    "CREATE TABLE CHILD (ID INT NOT NULL, PARENT_ID INT, LABEL VARCHAR(50), CONSTRAINT PK_CHILD PRIMARY KEY (ID), "
    "CONSTRAINT FK_CHILD_PARENT FOREIGN KEY (PARENT_ID) REFERENCES PARENT (ID) ON DELETE CASCADE)",
    "CREATE INDEX IX_CHILD_LABEL ON CHILD (LABEL)",
    "COMMENT ON TABLE PARENT IS 'tabla padre'",
    "COMMENT ON COLUMN CHILD.LABEL IS 'etiqueta'",
    "CREATE VIEW V_PARENT AS SELECT ID, CODE FROM PARENT",
    "CREATE FUNCTION F(X INT) RETURNS INT RETURN X + 1",
    "CREATE PROCEDURE P(IN X INT) MODIFIES SQL DATA BEGIN ATOMIC DECLARE Y INT; SET Y = X; END",
]


@pytest.fixture(scope="module")
def connection() -> Iterator[Any]:
    import jaydebeapi

    conn = jaydebeapi.connect(
        "org.hsqldb.jdbc.JDBCDriver", "jdbc:hsqldb:mem:util_bbdd_gold", ["SA", ""], os.environ[JAR_ENV]
    )
    cursor = conn.cursor()
    for stmt in DDL:
        cursor.execute(stmt)
    cursor.close()
    try:
        yield conn
    finally:
        conn.close()


@pytest.fixture
def source(connection: Any) -> CatalogSource:
    return CatalogSource(
        get_catalog_dialect("hsqldb"), DbapiCatalogExecutor(connection, "qmark"), source_id="hsqldb:mem:util_bbdd_gold"
    )


def test_full_snapshot(source: CatalogSource) -> None:
    s = source.snapshot()  # schema actual (SET SCHEMA) por VALUES (CURRENT_SCHEMA)
    assert s.schema == "ZZ_GOLD"
    assert [(t.name, t.comment) for t in s.tables()] == [("CHILD", None), ("PARENT", "tabla padre")]
    assert s.views()[0].definition is not None and "SELECT" in s.views()[0].definition
    cols = {c.name: c for c in s.columns("PARENT")}
    assert (cols["ID"].identity, cols["CODE"].data_type, cols["CODE"].nullable) == (
        "by default",
        "CHARACTER VARYING(20)",
        False,
    )
    assert (cols["AMOUNT"].precision, cols["AMOUNT"].scale, cols["AMOUNT"].data_type) == (12, 2, "NUMERIC(12,2)")
    assert {c.name: c.comment for c in s.columns("CHILD")}["LABEL"] == "etiqueta"
    pk = s.primary_key("PARENT")
    assert pk is not None and (pk.name, pk.columns) == ("PK_PARENT", ("ID",))
    assert [(u.name, u.columns) for u in s.uniques("PARENT")] == [("UK_PARENT_CODE", ("CODE",))]
    assert [c.name for c in s.checks("PARENT")] == ["CK_AMOUNT"]  # sin los NOT NULL SYS_CT_*
    fk = s.foreign_keys("CHILD")[0]
    assert (fk.name, fk.ref_table, fk.ref_columns, fk.on_delete) == ("FK_CHILD_PARENT", "PARENT", ("ID",), "CASCADE")
    indexes = {ix.name: ix for ix in s.indexes("CHILD")}
    assert indexes["IX_CHILD_LABEL"].columns == ("LABEL",) and not indexes["IX_CHILD_LABEL"].unique
    assert indexes["PK_CHILD"].primary
    assert [(i.table, i.column) for i in s.identity("PARENT")] == [("PARENT", "ID")]
    routines = {r.name: r for r in s.routines()}
    assert routines["F"].routine_type == "FUNCTION" and routines["F"].definition.startswith("CREATE FUNCTION")  # type: ignore[union-attr]
    assert routines["P"].routine_type == "PROCEDURE"
    params = s.routine_parameters(RoutineKey("F", routines["F"].signature))
    assert [(p.name, p.mode, p.data_type) for p in params] == [("X", "IN", "INTEGER")]
    database = s.database()
    assert database is not None and database.version.startswith("HSQLDB 2.")


def test_one_query_per_kind_and_lowercase_names(source: CatalogSource, connection: Any) -> None:
    calls: list[str] = []
    executor = source.executor
    original = executor.fetch_all

    def counting(sql: str, params: Any) -> list[tuple[Any, ...]]:
        calls.append(sql)
        return original(sql, params)

    executor.fetch_all = counting  # type: ignore[method-assign]
    s = source.snapshot("zz_gold", kinds=ALL_KINDS)  # minúsculas → ZZ_GOLD (normalize_name)
    assert len(calls) == len(ALL_KINDS)
    filtered = source.snapshot("zz_gold", kinds={Kind.COLUMNS}, tables=["child"])
    assert {c.table for c in filtered.data[Kind.COLUMNS]} == {"CHILD"}
    assert s.schema == "ZZ_GOLD"
