def _run(target: TypesTarget, statements: tuple[str, ...], *, ignore_errors: bool) -> None:
    eng = create_engine(os.environ[target.url_env], isolation_level="AUTOCOMMIT")
    try:
        with eng.connect() as conn:
            for stmt in statements:
                try:
                    conn.execute(text(stmt))
                except Exception:  # noqa: BLE001 - objeto inexistente en la limpieza
                    if not ignore_errors:
                        raise
    finally:
        eng.dispose()


@pytest.fixture(scope="module", params=_targets(), ids=lambda t: t.engine)
def target(request: pytest.FixtureRequest) -> Iterator[TypesTarget]:
    t: TypesTarget = request.param
    reason = skip_reason(t.engine, t.url_env)
    if reason:
        pytest.skip(reason)
    _run(t, t.drop, ignore_errors=True)
    _run(t, t.create, ignore_errors=False)
    try:
        yield t
    finally:
        _run(t, t.drop, ignore_errors=True)


def _extractor(engine: str, variant: str, mgr: SyncDatabaseManager) -> Any:
    from util_bbdd.migrate.extractors.mariadb import MariaDBSchemaExtractor
    from util_bbdd.migrate.extractors.mysql import MariaDBFullTypeSchemaExtractor, MySQLSchemaExtractor
    from util_bbdd.migrate.extractors.oracle import OracleSchemaExtractor
    from util_bbdd.migrate.extractors.postgresql import PostgreSQLSchemaExtractor
    from util_bbdd.migrate.extractors.sqlserver import SQLServerSchemaExtractor

    if engine == "mysql":
        return MySQLSchemaExtractor(mgr, full_column_types=variant == "full_types")
    if engine == "mariadb":
        return MariaDBFullTypeSchemaExtractor(mgr) if variant == "full_types" else MariaDBSchemaExtractor(mgr)
    return {
        "postgresql": PostgreSQLSchemaExtractor,
        "sqlserver": SQLServerSchemaExtractor,
        "oracle": OracleSchemaExtractor,
    }[engine](mgr)


def _ours(name: Any) -> bool:
    return str(name).lower().startswith(P)


def _ir(extractor: Any, schema: str) -> dict[str, Any]:
    return {
        kind: _call(
            lambda fn=fn, kind=kind: (
                sorted(
                    (dataclasses.asdict(obj) for obj in fn(schema) if _ours(obj.name) or _ours(obj.package_name or "")),
                    key=lambda d: (
                        d["name"],
                        d.get("routine_type", ""),
                        d.get("package_name") or "",
                        d.get("body", ""),
                    ),
                )
                if kind == "routines"
                else sorted((dataclasses.asdict(obj) for obj in fn(schema) if _ours(obj.name)), key=lambda d: d["name"])
            )
        )
        for kind, fn in (
            ("tables", extractor.extract),
            ("views", extractor.extract_views),
            ("routines", extractor.extract_routines),
        )
    }


class _OursOnly:
    """Extractor que deja solo los objetos ``zz_mt_*`` (el schema de Oracle es el del usuario del banco)."""

    def __init__(self, inner: Any) -> None:
        self._inner = inner

    def extract(self, schema: str) -> list[Any]:
        return [t for t in self._inner.extract(schema) if _ours(t.name)]

    def extract_views(self, schema: str) -> list[Any]:
        return [v for v in self._inner.extract_views(schema) if _ours(v.name)]

    def extract_routines(self, schema: str) -> list[Any]:
        return [r for r in self._inner.extract_routines(schema) if _ours(r.name) or _ours(r.package_name or "")]


def _ddl(engine: str, mgr: SyncDatabaseManager, schema: str, monkeypatch: pytest.MonkeyPatch) -> dict[str, Any]:
    """DDL emitido hacia cada destino: lo que de verdad depende del IR (tipos, longitudes, defaults, identidad)."""
    from util_bbdd.migrate import planner as planner_module
    from util_bbdd.migrate.planner import MigrationPlanner

    for name in (
        "OracleSchemaExtractor",
        "MariaDBSchemaExtractor",
        "MariaDBFullTypeSchemaExtractor",
        "MySQLSchemaExtractor",
        "SQLServerSchemaExtractor",
        "PostgreSQLSchemaExtractor",
    ):
        cls = getattr(planner_module, name)
        monkeypatch.setattr(planner_module, name, lambda *a, _cls=cls, **k: _OursOnly(_cls(*a, **k)), raising=True)
    out: dict[str, Any] = {}
    for target_engine in ("oracle", "mariadb", "mysql", "sqlserver", "postgresql"):
        if target_engine == engine:
            continue
        plan = MigrationPlanner(source_engine=engine, target_engine=target_engine).plan(mgr, schema)
        ddl = plan.emit_ddl()
        out[target_engine] = {
            "ddl": ddl.splitlines(),
            "warnings": sorted({f"{w.code}:{w.table}:{w.column}" for w in plan.warnings}),
        }
    return out


def test_migrate_ir_matches_golden(target: TypesTarget, monkeypatch: pytest.MonkeyPatch) -> None:
    db_type, params = target.manager_args()
    with SyncDatabaseManager(db_type, params, use_pool=False) as mgr:
        result: dict[str, Any] = {
            variant: _ir(_extractor(target.engine, variant, mgr), target.schema) for variant in target.variants
        }
        result["ddl"] = _ddl(target.engine, mgr, target.schema, monkeypatch)
    for variant in target.variants:
        assert result[variant]["tables"] and not isinstance(result[variant]["tables"], dict), result[variant]["tables"]
    serialized = _ORACLE_IDENTITY_SEQ.sub(
        "ISEQ$$_<n>", json.dumps(result, indent=1, ensure_ascii=False, sort_keys=True)
    )
    _compare(GOLDEN_DIR / f"{target.engine}_migrate_ir.json", serialized + "\n")
