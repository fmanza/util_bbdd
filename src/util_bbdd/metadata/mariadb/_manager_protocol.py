"""Protocolos internos que describen los contratos del manager usados por los adaptadores MariaDB."""

from __future__ import annotations

from typing import Any, Protocol

from ...metadata.adapters.shared._base_manager_protocol import BaseAsyncManagerProtocol, BaseSyncManagerProtocol
from ...results import RowOrNone, Rows
from ..model import ColumnMeta, ForeignKeyMeta, IndexMeta, PrimaryKeyMeta, TableMeta


class MariaDBSyncManagerProtocol(BaseSyncManagerProtocol, Protocol):
    """Contrato mínimo que MariaDBSyncAdapter espera del SyncDatabaseManager."""

    def execute_custom_many(self, sql: str, params: dict[str, Any] | None = None) -> Rows: ...

    def execute_custom_one(self, sql: str, params: dict[str, Any] | None = None) -> RowOrNone: ...

    def get_tables(self) -> list[TableMeta]: ...

    def get_columns(self, tabla: str) -> list[ColumnMeta]: ...

    def get_primary_keys(self, tabla: str) -> PrimaryKeyMeta | None: ...

    def get_foreign_keys(self, tabla: str) -> list[ForeignKeyMeta]: ...

    def get_indices(self, tabla: str) -> list[IndexMeta]: ...

    def execute_query_many(self, query_name: str, **kwargs: Any) -> Rows: ...


class MariaDBAsyncManagerProtocol(BaseAsyncManagerProtocol, Protocol):
    """Contrato mínimo que MariaDBAsyncAdapter espera del AsyncDatabaseManager."""

    async def execute_custom_many(self, sql: str, params: dict[str, Any] | None = None) -> Rows: ...

    async def execute_custom_one(self, sql: str, params: dict[str, Any] | None = None) -> RowOrNone: ...

    async def get_tables(self) -> list[TableMeta]: ...

    async def get_columns(self, tabla: str) -> list[ColumnMeta]: ...

    async def get_primary_keys(self, tabla: str) -> PrimaryKeyMeta | None: ...

    async def get_foreign_keys(self, tabla: str) -> list[ForeignKeyMeta]: ...

    async def get_indices(self, tabla: str) -> list[IndexMeta]: ...

    async def execute_query_many(self, query_name: str, **kwargs: Any) -> Rows: ...


__all__: list[str] = ["MariaDBAsyncManagerProtocol", "MariaDBSyncManagerProtocol"]
