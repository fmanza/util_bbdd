"""Emisor DDL para Oracle.

Responsabilidades:
  - Generar CREATE TABLE con identificadores en "MAYÚSCULAS" (double-quoted).
  - Emitir CREATE SEQUENCE + CREATE OR REPLACE TRIGGER para columnas AUTO_INCREMENT.
  - Emitir COMMENT ON TABLE / COMMENT ON COLUMN para comentarios.
  - Ordenar tablas topológicamente (FKs primero la tabla referenciada).
  - Detectar FKs circulares y emitirlas como ALTER TABLE al final.
  - Emitir FK externas como ALTER TABLE con comentario al final del script.
  - Omitir ON UPDATE en FKs (Oracle solo soporta ON DELETE CASCADE/SET NULL).
  - Incluir comentarios -- AVISO: para tipos sin equivalente exacto.

Nota sobre identificadores Oracle:
  Los identificadores se emiten en mayúsculas y entre comillas dobles ("NAME")
  para preservar el nombre exacto. Oracle almacena identificadores sin comillas
  en mayúsculas, y entre comillas respetando la capitalización original.
  Usar siempre mayúsculas garantiza comportamiento predecible.

Secuencias y triggers para AUTO_INCREMENT:
  Oracle < 12c no tiene columnas IDENTITY nativas. Se genera el patrón clásico:
    CREATE SEQUENCE "TABLE_SEQ" START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
    CREATE OR REPLACE TRIGGER "TRG_TABLE"
      BEFORE INSERT ON "TABLE" FOR EACH ROW
    BEGIN
      IF :NEW."COL" IS NULL THEN
        SELECT "TABLE_SEQ".NEXTVAL INTO :NEW."COL" FROM DUAL;
      END IF;
    END;
  Oracle 12c+ tiene GENERATED AS IDENTITY; v1 usa el patrón clásico por
  compatibilidad con Oracle 11g y versiones anteriores.
"""

from __future__ import annotations

import re

from typing import Literal

from .._compat.identifier_rules import MAX_ORACLE_IDENTIFIER_LENGTH, truncate_identifier
from ..ir.models import CanonicalColumn, CanonicalFK, CanonicalRoutine, CanonicalTable, CanonicalView, MigrationWarning
from ._default_fallback import default_fallback_warning
from ._index_names import claim_index_name
from ._trailing_comment import join_definitions, with_trailing_comment
from .mariadb import _topological_sort, _topological_sort_views

OracleIdentityMode = Literal["sequence_trigger", "identity_by_default_on_null"]

_VALID_ORACLE_IDENTITY_MODES: frozenset[str] = frozenset({"sequence_trigger", "identity_by_default_on_null"})

# Oracle ON DELETE acciones soportadas
_ORACLE_ON_DELETE_SUPPORTED: frozenset[str] = frozenset({"CASCADE", "SET NULL"})

# Traducción de defaults MariaDB a equivalentes Oracle
_MARIADB_TO_ORA_DEFAULTS: dict[str, str] = {
    "NOW()": "SYSDATE",
    "CURRENT_TIMESTAMP": "SYSDATE",
    "CURRENT_DATE": "TRUNC(SYSDATE)",
    "CURDATE()": "TRUNC(SYSDATE)",
    "CURTIME()": "NULL",
    "NULL": "NULL",
    "0": "0",
    "1": "1",
    "SYSDATE": "SYSDATE",
    "SYSTIMESTAMP": "SYSTIMESTAMP",
    "TRUE": "1",
    "FALSE": "0",
}


_PLSQL_BLOCK_RE: re.Pattern[str] = re.compile(
    r"^\s*CREATE\s+(?:OR\s+REPLACE\s+)?(?:TRIGGER|PROCEDURE|FUNCTION|PACKAGE|TYPE)\b", re.IGNORECASE
)


def _is_plsql_block(statement: str) -> bool:
    """True si la primera línea con SQL (tras los comentarios ``--``) crea un bloque PL/SQL."""
    code = "\n".join(line for line in statement.splitlines() if not line.strip().startswith("--"))
    return bool(_PLSQL_BLOCK_RE.match(code))


def _pk_constraint_name(table: CanonicalTable) -> str:
    return truncate_identifier(f"PK_{table.name.upper()}", MAX_ORACLE_IDENTIFIER_LENGTH)[0]


def _dq(name: str) -> str:
    """Escapa un identificador Oracle con comillas dobles (uppercase)."""
    return f'"{name.upper().replace(chr(34), chr(34) + chr(34))}"'


def _seq_name(table_name: str) -> str:
    """Genera el nombre de secuencia para una tabla (max 30 chars, único por hash)."""
    raw = f"{table_name.upper()}_SEQ"
    return truncate_identifier(raw, MAX_ORACLE_IDENTIFIER_LENGTH)[0]


def _trg_name(table_name: str) -> str:
    """Genera el nombre de trigger para una tabla (max 30 chars, único por hash)."""
    raw = f"TRG_{table_name.upper()}"
    return truncate_identifier(raw, MAX_ORACLE_IDENTIFIER_LENGTH)[0]


class OracleDDLEmitter:
    """Genera DDL Oracle desde IR canónico.

    Emite:
    - CREATE TABLE con columnas, PK inline y FKs internas (no circulares).
    - CREATE SEQUENCE + CREATE OR REPLACE TRIGGER por cada columna AUTO_INCREMENT
      (modo "sequence_trigger", compatible con Oracle 11g).
    - O bien GENERATED BY DEFAULT ON NULL AS IDENTITY inline en la columna
      (modo "identity_by_default_on_null", requiere Oracle 12c+).
    - COMMENT ON TABLE / COMMENT ON COLUMN para tablas y columnas con comentarios.
    - CREATE INDEX para índices no-PK.
    - ALTER TABLE ... ADD CONSTRAINT para FKs circulares y externas.
    - CREATE OR REPLACE VIEW para vistas.

    Args:
        oracle_identity_mode: Cómo emitir columnas AUTO_INCREMENT en Oracle destino.
            - "sequence_trigger" (por defecto): patrón clásico CREATE SEQUENCE +
              CREATE OR REPLACE TRIGGER, compatible con Oracle 11g y anteriores.
            - "identity_by_default_on_null": emite GENERATED BY DEFAULT ON NULL AS IDENTITY
              inline en la columna; no genera SEQUENCE ni TRIGGER. Requiere Oracle 12c+.

    Raises:
        ValueError: Si oracle_identity_mode no es un valor reconocido.
    """

    def __init__(
        self,
        oracle_identity_mode: OracleIdentityMode = "sequence_trigger",
    ) -> None:
        if oracle_identity_mode not in _VALID_ORACLE_IDENTITY_MODES:
            raise ValueError(
                f"oracle_identity_mode '{oracle_identity_mode}' no es válido. "
                f"Valores aceptados: {sorted(_VALID_ORACLE_IDENTITY_MODES)}"
            )
        self._identity_mode: OracleIdentityMode = oracle_identity_mode

    # ─── API pública ──────────────────────────────────────────────────────────

    def emit(
        self,
        tables: list[CanonicalTable],
        views: list[CanonicalView] | None = None,
        routines: list[CanonicalRoutine] | None = None,
    ) -> str:
        """Genera el script DDL Oracle completo listo para guardar en fichero .sql.

        Returns:
            Script SQL para SQL*Plus/SQLcl: cada sentencia termina en ``;`` y cada bloque PL/SQL (trigger, rutina) en
            una línea ``/`` (sin ella, las sentencias siguientes se añadirían al bloque).
        """
        stmts = self.emit_statements(tables, views, routines)
        return "\n\n".join(f"{stmt}\n/" if _is_plsql_block(stmt) else f"{stmt};" for stmt in stmts) + "\n"

    def emit_statements(
        self,
        tables: list[CanonicalTable],
        views: list[CanonicalView] | None = None,
        routines: list[CanonicalRoutine] | None = None,
    ) -> list[str]:
        """Genera lista de sentencias DDL individuales sin ';' al final.

        Orden de emisión:
        1. CREATE TABLE (ordenadas topológicamente)
        2. CREATE SEQUENCE + CREATE OR REPLACE TRIGGER (AUTO_INCREMENT)
        3. COMMENT ON TABLE / COMMENT ON COLUMN
        4. CREATE [UNIQUE] INDEX (no-PK)
        5. ALTER TABLE ADD CONSTRAINT (FKs circulares)
        6. ALTER TABLE ADD CONSTRAINT (FKs externas, con comentario)
        7. CREATE OR REPLACE VIEW (ordenadas topológicamente)
        8. CREATE OR REPLACE PROCEDURE/FUNCTION
        """
        ordered, circular_fk_pairs = _topological_sort(tables)

        external_fk_pairs: list[tuple[str, CanonicalFK]] = [
            (t.name, fk) for t in ordered for fk in t.foreign_keys if fk.is_external
        ]

        statements: list[str] = []

        # CREATE TABLE
        for table in ordered:
            skip_fk_names = {fk.name for _, fk in circular_fk_pairs if _ == table.name}
            statements.append(self._emit_create_table(table, skip_fk_names=skip_fk_names))

        # SEQUENCE + TRIGGER para AUTO_INCREMENT
        for table in ordered:
            statements.extend(self._emit_sequences_and_triggers(table))

        # COMMENT ON TABLE / COMMENT ON COLUMN
        for table in ordered:
            statements.extend(self._emit_comments(table))

        # CREATE INDEX (A3: el nombre de índice es único en el schema; las PK crean un índice con su nombre)
        taken_names: set[str] = {_pk_constraint_name(t) for t in ordered if t.primary_key}
        for table in ordered:
            statements.extend(self._emit_indexes(table, taken_names))

        # ALTER TABLE (FKs circulares)
        for table_name, fk in circular_fk_pairs:
            statements.append(self._emit_alter_table_add_fk(table_name, fk))

        # ALTER TABLE (FKs externas)
        for table_name, fk in external_fk_pairs:
            fk_stmt = self._emit_alter_table_add_fk(table_name, fk)
            stmt = (
                f"-- FK externa: {_dq(fk.name)} en {_dq(table_name)} referencia "
                f"{_dq(fk.ref_table)} (fuera del schema migrado) — verificar que existe\n"
                f"{fk_stmt}"
            )
            statements.append(stmt)

        # Vistas DESPUÉS de todas las tablas
        statements.extend(self._emit_view_statements(views))

        # Rutinas AL FINAL
        statements.extend(self._emit_routine_statements(routines))

        return statements

    # ─── CREATE TABLE ─────────────────────────────────────────────────────────

    def _emit_create_table(self, table: CanonicalTable, skip_fk_names: set[str]) -> str:
        lines: list[str] = [f"CREATE TABLE {_dq(table.name)} ("]
        comment_lines: list[str] = []
        ddl_lines: list[str] = []

        for col in table.columns:
            line = self._emit_column(col, table.name)
            if col.omit:
                comment_lines.append(line)
            else:
                ddl_lines.append(line)

        if table.primary_key:
            pk_name = _pk_constraint_name(table)
            pk_cols = ", ".join(_dq(c) for c in table.primary_key)
            ddl_lines.append(f"    CONSTRAINT {_dq(pk_name)} PRIMARY KEY ({pk_cols})")

        for fk in table.foreign_keys:
            if fk.is_external:
                continue
            if fk.name in skip_fk_names:
                continue
            ddl_lines.append(self._emit_fk_inline(fk))

        if not ddl_lines:
            comment_lines.append("    -- ERROR: tabla sin columnas activas tras omisión de tipos incompatibles")

        body_parts: list[str] = []
        if comment_lines:
            body_parts.append("\n".join(comment_lines))
        if ddl_lines:
            body_parts.append(join_definitions(ddl_lines))

        lines.append("\n".join(body_parts))
        lines.append(")")

        return "\n".join(lines)

    def _emit_column(self, col: CanonicalColumn, table_name: str) -> str:
        if col.omit:
            comment = col.ddl_comment or f"-- AVISO: columna '{col.original_name}' omitida"
            return f"    {comment}"

        parts = [f"    {_dq(col.name)}", col.target_type]

        if col.auto_increment and self._identity_mode == "identity_by_default_on_null":
            parts.append("GENERATED BY DEFAULT ON NULL AS IDENTITY")

        # Oracle exige DEFAULT antes de las restricciones en línea (NOT NULL): "NOT NULL DEFAULT x" es ORA-03076.
        # Oracle no usa AUTO_INCREMENT en la columna; la secuencia lo gestiona
        if col.default is not None and not col.auto_increment:
            default_val = _format_default_oracle(col.default)
            parts.append(f"DEFAULT {default_val}")
            fallback_warning = default_fallback_warning(
                raw_value=col.default,
                formatted_value=default_val,
                table=table_name,
                column=col.name,
                source_type=col.oracle_type,
                target_type=col.target_type,
            )
            if fallback_warning is not None and fallback_warning not in col.warnings:
                col.warnings.append(fallback_warning)

        if not col.nullable:
            parts.append("NOT NULL")

        line = " ".join(parts)

        trailing: list[str] = []
        if col.ddl_comment:
            aviso = col.ddl_comment.lstrip("- ").strip()
            if aviso:
                trailing.append(aviso)

        if trailing:
            line = with_trailing_comment(line, "-- " + " | ".join(trailing))

        return line

    def _emit_fk_inline(self, fk: CanonicalFK) -> str:
        cols = ", ".join(_dq(c) for c in fk.columns)
        ref_cols = ", ".join(_dq(c) for c in fk.ref_columns)
        stmt = f"    CONSTRAINT {_dq(fk.name)} FOREIGN KEY ({cols}) REFERENCES {_dq(fk.ref_table)} ({ref_cols})"
        on_delete = (fk.on_delete or "").strip().upper()
        if on_delete in _ORACLE_ON_DELETE_SUPPORTED:
            stmt += f" ON DELETE {on_delete}"
        return stmt

    def _emit_alter_table_add_fk(self, table_name: str, fk: CanonicalFK) -> str:
        fk_inline = self._emit_fk_inline(fk).strip()
        return f"ALTER TABLE {_dq(table_name)} ADD {fk_inline}"

    # ─── SEQUENCE + TRIGGER (AUTO_INCREMENT) ──────────────────────────────────

    def _emit_sequences_and_triggers(self, table: CanonicalTable) -> list[str]:
        """Genera UN par SEQUENCE + TRIGGER para la primera columna AUTO_INCREMENT.

        Oracle soporta una sola SEQUENCE/TRIGGER por tabla en el patrón clásico.
        Si hay múltiples columnas AUTO_INCREMENT se usa solo la primera; el resto
        genera MigrationWarning (MIG-08, AUDIT_CODE 2026-09-22) — antes se
        ignoraban en silencio (ni SEQUENCE/TRIGGER ni aviso) — y debería
        mapearse con valores DEFAULT fijos o revisarse manualmente.

        En modo "identity_by_default_on_null" la cláusula IDENTITY ya va inline
        en la columna, por lo que no se emite ni SEQUENCE ni TRIGGER.
        """
        if self._identity_mode == "identity_by_default_on_null":
            return []
        stmts: list[str] = []
        auto_increment_cols = [col for col in table.columns if not col.omit and col.auto_increment]
        for index, col in enumerate(auto_increment_cols):
            if index > 0:
                table.warnings.append(
                    MigrationWarning(
                        table=table.name,
                        column=col.name,
                        oracle_type="AUTO_INCREMENT",
                        target_type="(sin SEQUENCE/TRIGGER)",
                        message=(
                            f"Tabla '{table.name}': columna '{col.name}' es AUTO_INCREMENT pero "
                            "Oracle solo soporta un SEQUENCE/TRIGGER por tabla en este patrón; ya "
                            f"se generó para '{auto_increment_cols[0].name}'. Revisar manualmente: "
                            f"usar un DEFAULT fijo o un mecanismo alternativo para '{col.name}'."
                        ),
                        severity="WARNING",
                    )
                )
                continue
            seq = _seq_name(table.name)
            trg = _trg_name(table.name)
            stmts.append(f"CREATE SEQUENCE {_dq(seq)}\n  START WITH 1\n  INCREMENT BY 1\n  NOCACHE\n  NOCYCLE")
            stmts.append(
                f"CREATE OR REPLACE TRIGGER {_dq(trg)}\n"
                f"  BEFORE INSERT ON {_dq(table.name)}\n"
                f"  FOR EACH ROW\n"
                f"BEGIN\n"
                f"  IF :NEW.{_dq(col.name)} IS NULL THEN\n"
                f"    SELECT {_dq(seq)}.NEXTVAL INTO :NEW.{_dq(col.name)} FROM DUAL;\n"
                f"  END IF;\n"
                f"END;"
            )
        return stmts

    # ─── COMMENT ON ───────────────────────────────────────────────────────────

    def _emit_comments(self, table: CanonicalTable) -> list[str]:
        """Genera COMMENT ON TABLE y COMMENT ON COLUMN para comentarios no vacíos."""
        stmts: list[str] = []
        if table.comment:
            escaped = table.comment.replace("'", "''")
            stmts.append(f"COMMENT ON TABLE {_dq(table.name)} IS '{escaped}'")
        for col in table.columns:
            if col.omit or not col.comment:
                continue
            escaped = col.comment.replace("'", "''")
            stmts.append(f"COMMENT ON COLUMN {_dq(table.name)}.{_dq(col.name)} IS '{escaped}'")
        return stmts

    # ─── Índices ──────────────────────────────────────────────────────────────

    def _emit_indexes(self, table: CanonicalTable, taken_names: set[str] | None = None) -> list[str]:
        pk_set = {c.upper() for c in table.primary_key}
        omitted_cols = {col.name.upper() for col in table.columns if col.omit}
        stmts: list[str] = []

        for idx in table.indexes:
            idx_col_set = {c.upper() for c in idx.columns}
            if idx_col_set == pk_set and idx.unique:
                continue
            if idx_col_set & omitted_cols:
                continue

            unique_kw = "UNIQUE " if idx.unique else ""
            cols = ", ".join(_dq(c) for c in idx.columns)
            name = claim_index_name(
                table,
                idx,
                taken_names if taken_names is not None else set(),
                max_length=MAX_ORACLE_IDENTIFIER_LENGTH,
                fold=str.upper,
                target_label="Oracle",
            )
            stmt = f"CREATE {unique_kw}INDEX {_dq(name)} ON {_dq(table.name)} ({cols})"
            stmts.append(stmt)

        return stmts

    # ─── Vistas ───────────────────────────────────────────────────────────────

    def _emit_view_statements(self, views: list[CanonicalView] | None) -> list[str]:
        active = [v for v in (views or []) if v.query]
        ordered, circular = _topological_sort_views(active)
        stmts: list[str] = [self._emit_create_view(v) for v in ordered]
        for v in circular:
            aviso = (
                f"-- AVISO: vista '{v.name}' participa en una dependencia circular "
                "— verificar orden de ejecución manualmente\n"
            )
            stmts.append(aviso + self._emit_create_view(v))
        return stmts

    def _emit_create_view(self, view: CanonicalView) -> str:
        lines: list[str] = []
        if view.warnings:
            lines.append("-- NOTE: requires manual review (see migration warnings)")
        if view.comment:
            lines.append(f"-- COMMENT: {view.comment.replace(chr(10), ' ')}")
        lines.append(f"CREATE OR REPLACE VIEW {_dq(view.name)} AS")
        lines.append(view.query)
        return "\n".join(lines)

    def _emit_routine_statements(self, routines: list[CanonicalRoutine] | None) -> list[str]:
        return [self._emit_create_routine(r) for r in (routines or [])]

    def _emit_create_routine(self, routine: CanonicalRoutine) -> str:
        lines: list[str] = []
        if routine.is_package_member:
            pkg = routine.package_name or routine.name
            return (
                f"-- PACKAGE MEMBER: {pkg}.{routine.name} ({routine.routine_type})\n"
                f"-- No direct equivalent in Oracle target; manual migration required"
            )
        lines.append(f"-- {routine.routine_type}: {_dq(routine.name)}")
        if routine.warnings:
            lines.append("-- NOTE: requires manual review (see migration warnings)")
        if routine.comment:
            lines.append(f"-- COMMENT: {routine.comment.replace(chr(10), ' ')}")
        if not routine.body:
            lines.append(
                f"-- TODO: {routine.routine_type} {_dq(routine.name)} — "
                f"body not available; manual implementation required"
            )
            return "\n".join(lines)
        lines.append(routine.body)
        return "\n".join(lines)


def _format_default_oracle(value: str) -> str:
    """Traduce un valor DEFAULT MariaDB a su equivalente Oracle."""
    if not value:
        return "NULL"

    v = value.strip()
    upper_v = v.upper()

    if upper_v in _MARIADB_TO_ORA_DEFAULTS:
        return _MARIADB_TO_ORA_DEFAULTS[upper_v]

    # Funciones temporales con argumento de precisión (ej. NOW(3)) → SYSTIMESTAMP en Oracle
    if re.match(
        r"^(NOW|CURRENT_TIMESTAMP|CURTIME)\s*\(\s*\d+\s*\)$",
        v,
        re.IGNORECASE,
    ):
        return "SYSTIMESTAMP"

    try:
        float(v)
        return v
    except ValueError:
        pass

    # String literal ya entrecomillado (convenio de todos los orígenes tras normalize_default): no volver a
    # entrecomillarlo, o saldría con comillas triplicadas.
    if len(v) >= 2 and v.startswith("'") and v.endswith("'"):
        return v

    escaped = v.replace("'", "''")
    return f"'{escaped}'"


