#!/usr/bin/env python3
"""Banco de pruebas de rendimiento de ``util_bbdd.dump.DumpOrchestrator`` contra motores reales.

Ejecuta el volcado real origen → destino en el mismo servidor (dos esquemas, ``dump_src`` → ``dump_dst``) y desglosa el
tiempo por fase instrumentando, solo dentro de este proceso, los métodos de ``dump``/``bulk`` (no modifica ``src/``).
Cada medición corre en un subproceso propio (memoria pico por medición) y se verifica con SQL: COUNT y SUM(PK) de origen
y destino por tabla, y una sonda de identidad (un INSERT sin PK tras el volcado, con rollback).

Sustituye al banco anterior de este fichero, que simulaba la copia con ``pd.to_sql`` sin llamar a ``DumpOrchestrator``
(hallazgo PF-07 de .ai/sessions/2026-09-25-performance-audit-dump/audit_report_dump_20260925.md).

Esquema (3 tablas encadenadas por FK):
    customers(customer_id PK, name, email, country, created_at)
    orders(order_id PK, customer_id FK, order_date, total_amount DECIMAL)
    order_items(item_id PK, order_id FK, product_name, quantity, unit_price DECIMAL)
El destino tiene PK de identidad (IDENTITY / AUTO_INCREMENT / GENERATED BY DEFAULT) e índice secundario en cada FK.
SQLite solo se mide como destino, con PostgreSQL de origen (el origen SQLite no está soportado).

Volúmenes (filas customers / orders / order_items):
    tiny 1K/2,5K/5K · small 10K/25K/50K · medium 100K/250K/500K · large 500K/1M/2M (3,5M filas)

Subcomandos:
    setup       crea esquemas, tablas origen (datos generados en el servidor) y tablas destino vacías
    run         ejecuta variantes (un subproceso por medición) y añade una línea JSON por medición a <out>/results.jsonl
    one         una medición (lo usa ``run``); imprime una línea JSON
    summarize   resume uno o varios results.jsonl en Markdown (mediana por motor × variante, fases y Δ frente a baseline)
    list        lista variantes y volúmenes

Credenciales: ``UTIL_BBDD_BENCH_PASSWORD`` (la de ``docker-compose.bench.yml``). Puertos: los del banco o
``UTIL_BBDD_BENCH_<MOTOR>_PORT``. Solo 127.0.0.1. **Apunta siempre a los contenedores del banco**: ``setup`` borra y
recrea ``dump_src``/``dump_dst`` (esquemas en PostgreSQL y SQL Server, bases en MySQL/MariaDB, usuarios en Oracle), y cada
medición recrea las tablas de ``dump_dst``. ``DumpConfig`` sin ``tables`` vuelca todo el esquema: no dejes tablas ajenas
en ``dump_src``.

Los informes Excel y el CSV de auditoría de cada medición van a un directorio temporal que se borra al terminar. Los
ficheros SQLite van a ``BENCH_DUMP_SQLITE_DIR`` (por defecto, ``<tmp>/util_bbdd_bench_dump``).

Uso:
    python scripts/bench_dump.py setup --engines postgresql,mysql,mssql,oracle --volume large
    python scripts/bench_dump.py run --engines postgresql --variants baseline,stream --volume large --repeat 3 --out bench_results/dump
    python scripts/bench_dump.py summarize bench_results/dump/results.jsonl
    python scripts/bench_dump.py list
"""

