def _skip_constraint_validation() -> None:
    """Variante ``nocheck``: rehabilita constraints sin revalidar datos (mide el coste de la validación)."""
    from sqlalchemy import text as _text

    from util_bbdd.dump import ConstraintManager
    from util_bbdd.dump._models import ConstraintResult

    def _enable_sqlserver(self: Any) -> list[Any]:
        res = []
        with self._engine.connect() as conn:
            for table in self._nocheck_tables:
                conn.execute(_text(f"ALTER TABLE {self._qt(table)} CHECK CONSTRAINT ALL"))  # sin WITH CHECK
                conn.commit()
                res.append(ConstraintResult(table, "ALL", self._dialect, "unverified"))
        return res

    def _enable_oracle(self: Any) -> list[Any]:
        res = []
        with self._engine.connect() as conn:
            for table, name in self._disabled:
                conn.execute(_text(f"ALTER TABLE {self._qt(table)} ENABLE NOVALIDATE CONSTRAINT {self._qi(name)}"))
                conn.commit()
                res.append(ConstraintResult(table, name, self._dialect, "unverified"))
        return res

    ConstraintManager._enable_sqlserver = _enable_sqlserver  # type: ignore[method-assign]
    ConstraintManager._enable_oracle = _enable_oracle  # type: ignore[method-assign]


