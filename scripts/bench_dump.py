SOURCE_OF = {"sqlite": "postgresql"}


def _verify(src_engine: Engine, engine: Engine, engine_key: str) -> dict[str, Any]:
    """Compara COUNT y SUM(pk) origen/destino por tabla y comprueba que el siguiente valor de identidad es > MAX."""
    pk = {"customers": "customer_id", "orders": "order_id", "order_items": "item_id"}
    out: dict[str, Any] = {"ok": True, "tables": {}}
    src_key = SOURCE_OF.get(engine_key, engine_key)
    with engine.connect() as conn, src_engine.connect() as sconn:
        for t in TABLES:
            q = "SELECT COUNT(*), SUM(CAST({pk} AS {big})) FROM {s}.{t}"
            casts = {"oracle": "NUMBER(19)", "mysql": "SIGNED", "mariadb": "SIGNED", "sqlite": "INTEGER"}
            big, sbig = casts.get(engine_key, "BIGINT"), casts.get(src_key, "BIGINT")
            src = tuple(sconn.execute(text(q.format(pk=pk[t], big=sbig, s=SRC, t=t))).one())
            dst = tuple(conn.execute(text(q.format(pk=pk[t], big=big, s=DST, t=t))).one())
            same = [int(x or 0) for x in src] == [int(x or 0) for x in dst]
            out["tables"][t] = {"src": [int(x or 0) for x in src], "dst": [int(x or 0) for x in dst], "same": same}
            out["ok"] &= same
    # Sonda de identidad: un INSERT sin PK tras el volcado no debe chocar con las filas cargadas (Fase 5a, PK sync).
    with engine.connect() as conn:
        try:
            conn.execute(text(f"INSERT INTO {DST}.customers (name) VALUES ('probe')"))
            out["identity_ok"] = True
        except SQLAlchemyError as exc:
            out["identity_ok"] = False
            out["identity_error"] = str(exc).splitlines()[0][:200]
        finally:
            conn.rollback()
    return out


def seed_audit_history(path: Path, n_rows: int) -> None:
    """Escribe ``n_rows`` registros de volcados anteriores (fechados en 2025) en el CSV de auditoría, con su formato."""
    with path.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.writer(fh, delimiter="\t")
        writer.writerow(["timestamp", "tabla", "motor", "operacion", "total_filas", "tiempo_seg", "sql"])
        writer.writerows(
            [f"2025-01-01 00:{(i // 60) % 60:02d}:{i % 60:02d}", f"{DST}.{TABLES[i % 3]}", "POSTGRESQL", "INSERT",
             5000, "0,125", "No"]
            for i in range(n_rows)
        )  # fmt: skip


def run_one(engine_key: str, variant: str, volume: str) -> dict[str, Any]:
    opts = dict(VARIANTS[variant])
    use_stream = opts.pop("stream", False)
    arraysize = opts.pop("arraysize", None)
    use_prefetch = opts.pop("prefetch", False)
    keep_target = opts.pop("keep_target", False)
    use_audit = opts.pop("audit", False)
    audit_history = opts.pop("audit_history", False)
    if opts.pop("skip_constraint_validation", False):
        _skip_constraint_validation()
    install_instrumentation(use_prefetch=use_prefetch)

    from util_bbdd.dump import DumpConfig, DumpOrchestrator

    # Informes Excel y CSV de auditoría: directorio temporal propio de la medición, borrado al terminar.
    work_dir = Path(tempfile.mkdtemp(prefix="bench_dump_"))
    audit_path = work_dir / "audit.csv" if use_audit else None
    if audit_path is not None and audit_history:
        seed_audit_history(audit_path, AUDIT_HISTORY_ROWS)
    src_engine = make_engine(SOURCE_OF.get(engine_key, engine_key), arraysize=arraysize)
    dst_engine = make_engine(engine_key)
    if not keep_target:
        reset_target(dst_engine, engine_key)
    source = src_engine.execution_options(stream_results=True) if use_stream else src_engine
    cfg = DumpConfig(
        source_engine=source,
        target_engine=dst_engine,
        source_schema=SRC,
        target_schema=DST,
        output_dir=work_dir,
        bulk_audit_path=audit_path,
        **opts,
    )
    record: dict[str, Any] = {
        "engine": engine_key,
        "variant": variant,
        "volume": volume,
        "rows": sum(VOLUMES[volume].values()),
        "driver": str(dst_engine.url.drivername),
        "ts": time.strftime("%Y-%m-%dT%H:%M:%S"),
    }
    t0 = perf_counter()
    try:
        orch = DumpOrchestrator(cfg)
        _add("init", perf_counter() - t0)
        result = orch.run()
        record["total_s"] = perf_counter() - t0
        record["status"] = {r.table_name: r.status for r in result.table_results}
        record["errors"] = {r.table_name: r.error_msg[:300] for r in result.table_results if r.error_msg}
        record["skipped_columns"] = {r.table_name: r.skipped_columns for r in result.table_results if r.skipped_columns}
        record["constraints"] = {
            s: sum(1 for c in result.constraint_results if c.status == s) for s in ("enabled", "failed", "unverified")
        }
        record["constraint_errors"] = [c.error_msg[:200] for c in result.constraint_results if c.status == "failed"]
        record["pk_sync"] = [f"{r.table_name}:{r.status}" for r in (result.pk_sync_results or [])]
        record["indexes"] = [f"{r.index_name}:{r.action}" for r in (result.index_results or [])]
        if result.audit_summary is not None:
            s = result.audit_summary
            record["audit"] = {
                "operaciones": s.total_operaciones,
                "filas_csv": s.total_filas,
                "audited_rows": s.audited_rows,
                "audit_failures": s.audit_failures,
            }
    except Exception as exc:  # noqa: BLE001 — el banco registra el fallo y sigue
        record["total_s"] = perf_counter() - t0
        record["exception"] = f"{type(exc).__name__}: {exc}"[:500]
        record["traceback"] = traceback.format_exc()[-1500:]
    record["phases"] = {k: round(v, 3) for k, v in sorted(STATS.items())}
    ph = STATS
    record["phases"]["prep_derived"] = round(
        ph.get("load", 0) - ph.get("read", 0) - ph.get("write", 0) - ph.get("reflect", 0) - ph.get("bulkcrud_init", 0),
        3,
    )
    record["peak_rss_mb"] = round(peak_rss_mb(), 1)
    try:
        record["verify"] = _verify(src_engine, dst_engine, engine_key)
    except SQLAlchemyError as exc:
        record["verify"] = {"ok": False, "error": str(exc)[:300]}
    record["rows_per_s"] = round(record["rows"] / record["total_s"]) if record.get("total_s") else None
    src_engine.dispose()
    dst_engine.dispose()
    shutil.rmtree(work_dir, ignore_errors=True)
    return record


def run_matrix(engines: list[str], variants: list[str], volume: str, repeat: int, out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    results = out / "results.jsonl"
    env = dict(os.environ)
    for engine_key in engines:
        for variant in variants:
            for i in range(repeat):
                cmd = [
                    sys.executable,
                    __file__,
                    "one",
                    "--engine",
                    engine_key,
                    "--variant",
                    variant,
                    "--volume",
                    volume,
                ]
                t = perf_counter()
                proc = subprocess.run(cmd, capture_output=True, text=True, env=env, check=False)
                line = next((ln for ln in reversed(proc.stdout.splitlines()) if ln.startswith("{")), None)
                if line is None:
                    rec = {"engine": engine_key, "variant": variant, "volume": volume, "crash": proc.stderr[-1500:]}
                    line = json.dumps(rec)
                with results.open("a", encoding="utf-8") as fh:
                    fh.write(line + "\n")
                rec = json.loads(line)
                print(
                    f"{engine_key:10} {variant:14} #{i + 1} total={rec.get('total_s', float('nan')):8.1f}s "
                    f"rows/s={rec.get('rows_per_s')} rss={rec.get('peak_rss_mb')}MB "
                    f"verify={rec.get('verify', {}).get('ok')} ident={rec.get('verify', {}).get('identity_ok')} exc={rec.get('exception', rec.get('crash', ''))[:120]} "
                    f"(wall {perf_counter() - t:.0f}s)",
                    flush=True,
                )


