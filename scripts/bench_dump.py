def _port(engine_key: str, default: int) -> int:
    return int(os.environ.get(f"UTIL_BBDD_BENCH_{engine_key.upper()}_PORT", default))


def make_url(engine_key: str) -> URL:
    if engine_key == "sqlite":
        # Fichero principal vacío; dump_src y dump_dst se adjuntan como esquemas (ATTACH) en cada conexión.
        return URL.create("sqlite", database=str(SQLITE_DIR / "main.db"))
    pw = os.environ.get("UTIL_BBDD_BENCH_PASSWORD")
    if not pw:
        raise SystemExit("Define UTIL_BBDD_BENCH_PASSWORD (la de docker-compose.bench.yml)")
    host = "127.0.0.1"
    if engine_key == "postgresql":
        return URL.create("postgresql+psycopg", "bench", pw, host, _port("postgres", 55432), "bench")
    if engine_key == "mysql":
        # root: el usuario bench solo tiene permisos sobre la base `bench`; el banco usa dos bases (dump_src/dump_dst).
        return URL.create("mysql+pymysql", "root", pw, host, _port("mysql", 53306), None)
    if engine_key == "mariadb":
        return URL.create("mariadb+pymysql", "root", pw, host, _port("mariadb", 53307), None)
    if engine_key == "mssql":
        return URL.create(
            "mssql+pyodbc",
            "sa",
            pw,
            host,
            _port("mssql", 51433),
            "bench",
            query={"driver": "ODBC Driver 18 for SQL Server", "TrustServerCertificate": "yes"},
        )
    if engine_key == "oracle":
        # system: crea los usuarios/esquemas DUMP_SRC y DUMP_DST.
        return URL.create(
            "oracle+oracledb", "system", pw, host, _port("oracle", 51521), None, query={"service_name": "FREEPDB1"}
        )
    raise ValueError(engine_key)


def make_engine(engine_key: str, *, arraysize: int | None = None) -> Engine:
    kwargs: dict[str, Any] = {"pool_size": 12, "max_overflow": 4, "pool_pre_ping": True, "pool_recycle": 3600}
    if engine_key == "oracle" and arraysize:
        kwargs["arraysize"] = arraysize
    if engine_key == "sqlite":
        SQLITE_DIR.mkdir(parents=True, exist_ok=True)
        engine = create_engine(make_url(engine_key), pool_size=12, max_overflow=4)

        @event.listens_for(engine, "connect")
        def _attach(dbapi_conn: Any, _rec: Any) -> None:
            cur = dbapi_conn.cursor()
            for s in (SRC, DST):
                cur.execute(f"ATTACH DATABASE '{(SQLITE_DIR / (s + '.db')).as_posix()}' AS {s}")
            cur.execute("PRAGMA foreign_keys = ON")
            cur.close()

        return engine
    return create_engine(make_url(engine_key), **kwargs)


