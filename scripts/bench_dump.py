def _fmt(x: float | None, d: int = 1) -> str:
    return "—" if x is None else f"{x:,.{d}f}".replace(",", "X").replace(".", ",").replace("X", ".")


def _ok(r: dict[str, Any]) -> bool:
    return bool(r.get("verify", {}).get("ok")) and all(s == "success" for s in r.get("status", {}).values())


def summarize(paths: list[Path]) -> str:
    """Mediana por motor × variante × volumen: total, Δ frente a baseline, memoria, fases y verificación."""
    rows = [json.loads(ln) for p in paths for ln in p.read_text(encoding="utf-8").splitlines() if ln.strip()]
    groups: dict[tuple[str, str, str], list[dict[str, Any]]] = defaultdict(list)
    for r in rows:
        if "engine" in r and "variant" in r:  # ignora líneas de otros bancos
            groups[(r.get("volume", "?"), r["engine"], r["variant"])].append(r)

    def med(rs: list[dict[str, Any]], key: str) -> float | None:
        vals = [r[key] for r in rs if r.get(key) is not None and "exception" not in r]
        return statistics.median(vals) if vals else None

    def med_phase(rs: list[dict[str, Any]], key: str) -> float | None:
        vals = [r["phases"].get(key, 0.0) for r in rs if "phases" in r and "exception" not in r]
        return statistics.median(vals) if vals else None

    variants = list(dict.fromkeys(["baseline", *VARIANTS, *(k[2] for k in groups)]))
    out = ["| Volumen | Motor | Variante | n | Total (s) | Δ vs baseline | RSS pico (MB) | "
           + " | ".join(SUMMARY_PHASES) + " | Verificación | Identidad |",
           "|---|---|---|---|---|---|---|" + "---|" * len(SUMMARY_PHASES) + "---|---|"]  # fmt: skip
    for vol in dict.fromkeys(k[0] for k in groups):
        for eng in ENGINES:
            base = med(groups.get((vol, eng, "baseline"), []), "total_s")
            for var in variants:
                rs = groups.get((vol, eng, var))
                if not rs:
                    continue
                total = med(rs, "total_s")
                delta = f"{(total / base - 1) * 100:+.0f} %" if total and base and var != "baseline" else "—"
                ok = f"{sum(_ok(r) for r in rs)}/{len(rs)}"
                ident = f"{sum(bool(r.get('verify', {}).get('identity_ok')) for r in rs)}/{len(rs)}"
                phases = " | ".join(_fmt(med_phase(rs, p), 2) for p in SUMMARY_PHASES)
                out.append(
                    f"| {vol} | {eng} | {var} | {len(rs)} | {_fmt(total)} | {delta} | {_fmt(med(rs, 'peak_rss_mb'), 0)} "
                    f"| {phases} | {ok} | {ident} |"
                )
    out.append("")
    out.append(
        "Mediana de las repeticiones sin excepción. En variantes con hilos (prefetch, ranges*, combo*) las fases se"
    )
    out.append(
        "suman entre hilos: compara solo el total. Verificación = COUNT y SUM(PK) iguales y todas las tablas `success`."
    )
    return "\n".join(out)


